#!/usr/bin/env bash
# Runs INSIDE the container (as the salt user). Generates a no-passphrase GPG
# key in the master's gpg_keydir if absent, then writes N base64-random secrets
# encrypted to that key into the pillar SLS that decrypt_pillar will decrypt.
set -euo pipefail

N="${1:?N required}"
KEYDIR=/etc/salt/gpgkeys
RECIPIENT=pillar@papurika.test
OUT=/home/salt/data/srv/pillar/secrets.sls

export GNUPGHOME="$KEYDIR"

if ! gpg --homedir "$KEYDIR" --list-secret-keys "$RECIPIENT" >/dev/null 2>&1; then
  echo ">>> generating gpg key in $KEYDIR" >&2
  gpg --homedir "$KEYDIR" --batch --pinentry-mode loopback --passphrase '' \
      --quick-generate-key "papurika pillar <$RECIPIENT>" default default never
fi

echo "# generated by gen-gpg-pillar.sh ($N secrets) — gitignored" > "$OUT"
echo "secrets:" >> "$OUT"
for i in $(seq 1 "$N"); do
  val=$(head -c 32 /dev/urandom | base64 | tr -d '\n')
  printf '  secret_%05d: |\n' "$i" >> "$OUT"
  printf '%s' "$val" \
    | gpg --homedir "$KEYDIR" --armor --batch --yes --trust-model always \
          --encrypt -r "$RECIPIENT" \
    | sed 's/^/    /' >> "$OUT"
done
echo ">>> wrote $N encrypted secrets to $OUT" >&2
